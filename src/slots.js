let nextIndex = 1;

export const CATEGORIES = RAW.map((category) => {
  const slots = category.items.map((item) => {
    const slot = {
      ...item,
      index: nextIndex,
      category: category.id,
      categoryLabel: category.label,
      keywords: Array.isArray(item.keywords) ? item.keywords : [],
    };
    nextIndex += 1;
    return slot;
  });
  const first = String(slots[0].index).padStart(2, "0");
  const last = String(slots[slots.length - 1].index).padStart(2, "0");
  return { id: category.id, label: category.label, range: `${first}–${last}`, slots };
});

export const SLOTS = CATEGORIES.flatMap((category) => category.slots);

