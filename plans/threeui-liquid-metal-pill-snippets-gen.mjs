import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const html = readFileSync(
  join(root, "src", "shaders", "liquid-metal-button", "liquid-metal-button.html"),
  "utf8",
);
const react = `import { LiquidMetalButton } from "../shaders/liquid-metal-button/LiquidMetalButton.tsx";
import "../shaders/threeui.css";

export function Scene() {
  return <LiquidMetalButton variant="pill" />;
}
`;
const node = `import { createServer } from "node:http";

const page = ${JSON.stringify(html)};

createServer((request, response) => {
  if (request.url !== "/") return response.writeHead(404).end();
  response.writeHead(200, { "content-type": "text/html; charset=utf-8" }).end(page);
}).listen(3000, () => console.log("http://localhost:3000"));
`;
const output = `/* Generated by plans/threeui-liquid-metal-pill-snippets-gen.mjs. */

export const THREEUI_LIQUID_METAL_PILL_SNIPPETS = {
  html: ${JSON.stringify(html)},
  react: ${JSON.stringify(react)},
  node: ${JSON.stringify(node)},
};

export const THREEUI_LIQUID_METAL_PILL_META = {
  id: "threeui-liquid-metal",
  name: "Liquid metal",
  blurb: "ThreeUI's WebGL 2 Sign up pill with live spectral hover and faceted press ripples.",
  states: ["default", "hover", "focus-visible", "active", "ripple"],
  keywords: ["liquid metal", "webgl2", "threeui", "sign up", "spectral", "ripple"],
};
`;

writeFileSync(join(root, "src", "buttons", "threeui-liquid-metal-pill.snippets.js"), output);
